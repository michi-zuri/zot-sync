// Turns tests/fixtures/*.json into tests/Fixtures.elm, one String per file,
// so Elm unit tests can decode exactly the JSON the integration tests serve.
// Run automatically by `npm test`; the generated module is not committed.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fixtureDir = join(here, "fixtures");

/** "items-top.json" -> "itemsTop" */
function elmName(file) {
  return file
    .replace(/\.json$/, "")
    .replace(/[-_.]+([a-zA-Z0-9])/g, (_, c) => c.toUpperCase())
    .replace(/^[A-Z]/, (c) => c.toLowerCase());
}

/** Elm string literal; Elm only accepts \u{XXXX} escapes, not JSON's \uXXXX. */
function elmString(text) {
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (code < 0x20) out += `\\u{${code.toString(16).padStart(4, "0")}}`;
    else out += ch;
  }
  return out + '"';
}

const files = readdirSync(fixtureDir).filter((f) => f.endsWith(".json")).sort();
const decls = files.map((file) => {
  // Re-serialise compactly: smaller module, and it validates the fixture is JSON.
  const json = JSON.stringify(JSON.parse(readFileSync(join(fixtureDir, file), "utf8")));
  return `{-| tests/fixtures/${file} -}\n${elmName(file)} : String\n${elmName(file)} =\n    ${elmString(json)}\n`;
});

const source = `module Fixtures exposing (${files.map(elmName).join(", ")})

{-| GENERATED by tests/generate-fixtures.mjs from tests/fixtures/*.json. Do not edit. -}


${decls.join("\n\n")}`;

writeFileSync(join(here, "Fixtures.elm"), source);
console.log(`Fixtures.elm: ${files.length} fixtures`);
